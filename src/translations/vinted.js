const pattern = (en, el, elMatch, enReplace) => ({ en, el, elMatch, enReplace });

// Product image descriptions are "<brand> <title>", so match any known title.
const englishTitles = Object.keys(translations).filter((key) => /^[A-Z][a-z-]+( [A-Za-z-]+)+$/.test(key) && /tee|T-shirt|top|shirt|long-sleeve|crew neck|jeans|trainers|cardigan|overshirt|flats|tote|belt|skirt|loafers/.test(key));
const escape = (text) => text.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
const titleGroup = (titles) => titles.map(escape).sort((a, b) => b.length - a.length).join("|");

export const vintedPatterns = [
  pattern(
    new RegExp(`^(.+) (${titleGroup(englishTitles)})$`),
    "$2 ($1)",
    new RegExp(`^(${titleGroup(englishTitles.map((title) => translations[title]))}) \\((.+)\\)$`),
    "$2 $1"
  ),
  pattern(/^(\d+) results$/, "$1 αποτελέσματα", /^(\d+) αποτελέσματα$/, "$1 results"),
  pattern(/^(.+) also has items from your favourites\.$/, "$1: κι άλλα προϊόντα από τα αγαπημένα σας.", /^(.+): κι άλλα προϊόντα από τα αγαπημένα σας\.$/, "$1 also has items from your favourites."),
  pattern(/^(\d+) add-ons? selected$/, "Επιλέχθηκαν $1 επιπλέον", /^Επιλέχθηκαν (\d+) επιπλέον$/, "$1 add-ons selected"),
  pattern(/^(£[\d.,]+) total$/, "$1 συνολικά", /^(£[\d.,]+) συνολικά$/, "$1 total"),
  pattern(/^(\d+) items from (.+)$/, "$1 προϊόντα από τον πωλητή $2", /^(\d+) προϊόντα από τον πωλητή (.+)$/, "$1 items from $2"),
];
